# Project paths, relative to the repo root. Every qmd sources this file, so
# moving or renaming a folder is a one-line change here.
#
# GFW pipeline versions. GFW reprocesses its whole history at each pipeline
# release (v4 2026-02-26, v5 2026-10-21) and relabels vessels, so everything
# made from one pull belongs to one version: the raw extracts, the tables built
# from them, the review sheets and identity cache, the crosswalk and permit
# groups 03 generates (they carry that pull's GFW labels), the grid, the model
# cache and the reports. Those paths end in the version, e.g.
# data/raw/gfw/v4/. Hand-made inputs (decisions, gear corrections, removals,
# survey dates), the GARFO lists, the PSIX cache and the non-GFW spatial layers
# are shared by every version. See planning/gfw_pipeline_v5_plan.qmd,
# Section 3.1.
#
# A qmd renders against one version, set with `-P pipeline:v5` (blank = the
# default below). It can also override any single entry through a Quarto
# parameter of the same name, e.g. `quarto render 02_build_grid.qmd -P
# interim_gfw:scratch/interim`, which lets a test run write somewhere other
# than the real data folders.

# The version a render uses when none is given. The analysed data so far is
# the 2026-10-06 pull, which is v4 (gfwr requests ":latest", which was v4 until
# 2026-10-21). Change this only when the analysis adopts a new version.
gfw_pipeline_default <- "v4"

# All project paths for one pipeline version
make_gfw_paths <- function(pipeline = gfw_pipeline_default) {
  stopifnot("pipeline must be a non-empty folder name such as \"v5\"" =
              is.character(pipeline) && length(pipeline) == 1 &&
              grepl("^[A-Za-z0-9][A-Za-z0-9_.-]*$", pipeline))

  # a version-specific folder, or a file inside one
  v <- function(dir, file = NULL) {
    if (is.null(file)) file.path(dir, pipeline) else file.path(dir, pipeline, file)
  }
  # a version-specific file kept next to its shared siblings in references/
  ref_v <- function(stem) sprintf("references/%s_%s.csv", stem, pipeline)

  list(
    pipeline      = pipeline,

    # GFW 4Wings pulls (01_pull_gfw.qmd)
    raw_gfw       = v("data/raw/gfw"),
    raw_vp        = v("data/raw/gfw", "gfw_vp_id.csv"),
    raw_afe       = v("data/raw/gfw", "gfw_afe_id.csv"),
    pull_info     = v("data/raw/gfw", "pull_info.csv"), # when the raw files were pulled
    processed_gfw = v("data/processed/gfw"),
    interim_gfw   = v("data/interim/gfw"),

    # spatial layers; the grid is built from the cells in the pull (02)
    aoi           = "data/sf/aoi/Orsted_AOI.shp",
    leases        = c("data/sf/owf/sfw/SFW.shp", "data/sf/owf/rwf/RWF.shp", "data/sf/owf/srw/SRW.shp"),
    fishnet       = v("data/sf/fishnet"),
    grid          = v("data/sf/fishnet", "gfw_grid_utm19n.gpkg"),

    # vessel review (03_review_vessels.qmd) and classification (04_classify_aggregate.qmd)
    evidence      = v("data/raw/vessel_evidence"),          # GFW identity API cache
    psix          = "data/raw/vessel_evidence/psix_lookups.csv", # USCG PSIX cache (not GFW, so shared)
    registries    = "data/raw/vessel_evidence/registries",  # GARFO permit lists, read only
    review        = v("data/processed/vessel_review"),      # generated review sheets
    removals      = "references/vessel_removals.csv",
    survey_dates  = "references/orsted_fv_survey_dates_*.csv", # Ørsted survey trips; every match is read
    survey_vessels = "references/orsted_survey_vessels.csv",  # survey-file vessel names -> MMSI
    decisions     = "references/vessel_decisions.csv",
    gear          = "references/vessel_gear.csv",           # gear corrections
    crosswalk     = ref_v("vessel_crosswalk"),      # generated by 03 from removals, survey dates, decisions
    permit_groups = ref_v("vessel_permit_groups"),  # generated by 03 from GARFO matches
    permit_codes  = "references/garfo_permit_codes.csv",
    # write-once snapshot of the fishing vessels in one GFW pipeline version,
    # written by 03; %s is the version, e.g. sprintf(roster, "v4"). Left as a
    # template because a later version's run reads an earlier version's roster.
    roster        = "references/fishing_roster_%s.csv",

    # analysis tables, covariates and weights (05_prepare_analysis.qmd onward)
    analysis      = v("data/processed/analysis"),
    bathy         = "data/sf/bathy/crm_vol1_2023_aoi.tif", # NCEI CRM Vol. 1 AOI subset, fetched by 05
    models        = v("data/processed/models"),   # fitted models, cached by fit_cached() (10 onward)
    explore       = v("reports/explore"),         # 06 figures/ and tables/ (gitignored)
    spatial       = v("reports/spatial"),         # 07 onward: figures/ and tables/ (gitignored)
    bag           = v("reports/bag"),             # 10: figures/, tables/, refit cache/ (gitignored)
    compare       = "reports/pipeline_compare",   # v4 vs v5 comparison (gitignored)
    basemap       = "references/basemap/aoi_ocean_utm19n.tif", # map background, EPSG:32619

    # Ørsted foundations and cables (02a). The foundation CSVs and GeoJSON
    # layouts are as supplied (read only); the references/ tables are
    # transcribed from published sources, each row citing its source. SFW's
    # Ørsted CSV is the primary source; the PSO report's Table 3, transcribed,
    # is kept as an independent check on its dates.
    layouts       = c(SFW = "data/sf/owf/sfw/turbines/South Fork Wind_25-07-25_25-07-25.geojson",
                      RWF = "data/sf/owf/rwf/turbines/Revolution Wind_26-01-19_26-01-19.geojson",
                      SRW = "data/sf/owf/srw/turbines/Sunrise Wind (Preliminary)_26-01-05_26-01-05.geojson"),
    rwf_foundations = "data/sf/owf/rwf/turbines/REV_Foundation Installation_Dates_Locations_2024-2025.csv",
    srw_foundations = "data/sf/owf/srw/turbines/SRW_Foundation Installation_Dates_Locations_2025.csv",
    sfw_foundations = "data/sf/owf/sfw/turbines/sfw_monopile_install_orsted.csv", # PSO id × position × day
    sfw_pso_dates = "references/sfw_foundation_dates.csv",    # PSO report Table 3 (check)
    cable_windows = "references/infra_cable_windows.csv",     # project × cable type works windows
    safety_zones  = "references/infra_safety_zones.csv",      # USCG 500 m zones: rule window per project
    infra         = "data/sf/infra/infrastructure.gpkg"       # written by 02a: foundations + cables
  )
}

# The default version's paths, for helpers and tests that take no parameters
gfw_paths <- make_gfw_paths()

# Paths for a render: the version from a non-empty `pipeline` parameter (else
# the default), then any non-empty parameter named like an entry applied on top
gfw_paths_with <- function(params = list()) {
  pipeline <- params$pipeline
  if (is.null(pipeline) || identical(pipeline, "")) pipeline <- gfw_pipeline_default
  base <- make_gfw_paths(pipeline)

  over <- params[setdiff(intersect(names(params), names(base)), "pipeline")]
  over <- over[!vapply(over, \(x) is.null(x) || identical(x, ""), logical(1))]
  utils::modifyList(base, over)
}
